# ---- 拉起窗口的"冷却期"与"确认宽限期"（v0.3.4 新增，修 BUG-035）----
#
# 【为什么需要冷却期？】
#   子进程从被拉起，到把"座位信息"（pid）写进数据库，中间要将近 1 秒
#   （Python 启动 + import tkinter）。在这 1 秒里，服务端问"窗口在跑吗"
#   得到的答案一直是"没有"—— 于是连点几下「立即显示」，
#   每次都会再拉起一个新进程（实测 20 个并发请求拉出了 13 个以上）。
#   加上冷却期：刚拉过就不要再拉，等它注册完。
#
# 【为什么还需要"确认宽限期"？】
#   守护线程现在靠"下一次检查时窗口还在不在"来判断启动成功与否（见 BUG-034）。
#   如果窗口注册得慢一点，就会把它误判成"启动失败"。
#   宽限期 > 检查间隔，才不会冤枉它。
FLOATING_SPAWN_COOLDOWN_SECONDS = 3    # 两次拉起的间隔下限（秒）
FLOATING_PENDING_GRACE_SECONDS = 6     # 拉起后至少等这么久才判定"它死了"（秒）

