# ---- 外观 ----
# ---- 整窗不透明度 ----
#
# ★★★【先把三个容易混的概念分清楚 —— 这里是本项目踩过的坑】★★★
#
#  ① **不透明度（opacity）**：我们代码里用的这个数。
#     1.0 = 完全不透明（一点也看不透）；0.3 = 很透。
#     tkinter 里叫 `-alpha`。
#
#  ② **"透明度 30%"**：中文口语里的说法，含义是"允许 30% 的光透过去"，
#     换算成不透明度是 **0.70**。
#     ⚠️ 这两个说法方向相反，差一点就写反 —— 用户第一次说
#     「默认为黑色 30%透明度」时，我们做成了"不透明度 0.30"（几乎全透），
#     后来和用户核对了才确认他要的是"透 30%"，也就是**不透明度 0.70**。
#     **凡是和透明度有关的设置，都要问清"是哪一头"。**
#
#  ③ **清晰度（锐利） vs 对比度（看得清）**：这是两件**不同**的事，
#     用户澄清过："字体清晰指的是字体分辨率保持高，在任何情况下不能因为
#     模糊像素低而看不清"。也就是说：
#         · 清晰 = 笔画边缘锐利、不发毛 —— 靠 **DPI 感知**保证（见 BUG-030），
#           **和透明度没有关系**：半透明只是让颜色等比变淡，边缘依然是锐的；
#         · 对比度 = 字和背景的亮度差 —— 这个**会**随不透明度下降而下降。
#     所以"把不透明度调到很低"损失的是**对比度**，不是清晰度。
#     结论：允许调透（用户要的），但界面上要说清"再透下去字会变淡、变难读"。
#
# 【取值】
#   · 默认 0.70 = 用户点名的"黑色背景 + 透明度 30%"
#   · 下限 0.30：再低就只剩一层影子了 —— 那时不是"不清晰"，
#     而是"根本读不出内容"，窗口也就失去意义了。这个下限是**可读性**的底线，
#     不是清晰度的底线。
#   · 上限 1.0 = 完全不透明
FLOATING_MIN_OPACITY = 0.30
# ★★【v0.4.2：默认不透明度 0.70 -> 0.90（用户当前设置）】
#   用户 2026-09-14 要求："不透明度默认设置为我的当前设置内容"。
