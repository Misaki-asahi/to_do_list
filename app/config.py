# ---- 跨站请求防护（v0.3.4 新增，修 BUG-043）----
#
# 【要防的是什么？】
#   服务只监听 127.0.0.1，外面的人连不上 —— 但【你自己浏览器里打开的任意网页】
#   可以向你本机的这个服务发请求：浏览器是"站在你这边"发的，
#   它不受"只监听本机"这件事的保护。
#
#   其中"不带请求体的 POST"属于浏览器的【简单请求】，不会触发跨域预检，
#   所以浏览器不拦。结果就是：一个恶意网页（或广告 iframe）就能
#   把你的悬浮窗关掉、把配色改掉、甚至调 /api/settings/shutdown 直接结束整个程序。
#
#   （能读数据的接口都要令牌，所以【待办内容泄不出去】；
#     这里要防的是"写"，也就是"被人远程按按钮"。）
#
# 【怎么防？】
#   浏览器发跨站请求时一定会带上 Origin 头（现代浏览器还会带 Sec-Fetch-Site），
#   所以只要"带了这个头、又不是本机来源"就直接 403 ——
#   本机自己打开的页面不受影响；悬浮窗进程走 urllib、不带这个头，也不受影响。
#
# 【为什么不做完整鉴权？】
#   这是本机个人工具，威胁模型的上限是"被骚扰"，不是"数据泄露"。
#   再加一套登录体系需要在"用户怎么拿到令牌"上绕一圈，不划算。
